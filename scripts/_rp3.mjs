import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await browser.newPage();
const logs=[];
page.on('console', m=>logs.push(m.text().slice(0,100)));
page.on('response', r=>{ const u=r.url(); if(u.includes('ok.ru')) logs.push(`${r.status()} ${u.slice(0,70)}`); });
await page.goto('http://127.0.0.1:4173/help.html',{waitUntil:'domcontentloaded'});
await page.evaluate(()=>{
  const f=document.createElement('iframe');
  f.src='https://ok.ru/videoembed/16626814290604';
  f.style.cssText='width:800px;height:450px';
  f.setAttribute('referrerpolicy','no-referrer');
  document.body.appendChild(f);
});
await page.waitForTimeout(6000);
const frames = page.frames().map(f=>f.url());
console.log('frames:', frames.join('\n  '));
console.log('logs:', logs.slice(0,8).join(' | '));
const text = await (async()=>{ try { const f=page.frames().find(f=>f.url().includes('ok.ru')); return f ? (await f.evaluate(()=>document.body.innerText.slice(0,120))) : 'no frame'; } catch(e){ return 'X:'+e.message; } })();
console.log('frame text:', text);
await browser.close();
